#!/usr/bin/env python3
"""Replace narration while preserving every encoded laboratory video packet.

The supplied French narration is generated by a neural speech model.
No human recording was made for this narration.
It must already follow the original 123 subtitle intervals and chapter timing.
This script never generates speech, edits subtitles or contacts a network.

  python scripts/video/remux-neural-video.py \
    --source original.mp4 --audio narration-complete.wav \
    --output narration-neurale.mp4 --report narration-report.json \
    --subtitles sous-titres-fr.srt

Only run after narration-complete.wav has been finalized and reviewed.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
from pathlib import Path
import re
import subprocess
import sys
import wave


AUDIO_FILTER = (
    "loudnorm=I=-18:TP=-2:LRA=7,"
    "alimiter=limit=0.63:level=false:latency=true,aresample=48000"
)


def run(command: list[str], log: Path | None = None) -> str:
    if log is None:
        return subprocess.check_output(command, text=True)
    with log.open("w", encoding="utf-8") as handle:
        result = subprocess.run(command, stdout=handle, stderr=handle)
    text = log.read_text(encoding="utf-8")
    if result.returncode:
        raise RuntimeError(f"Command failed ({result.returncode}); {log}\n" + "\n".join(text.splitlines()[-35:]))
    return text


def probe(path: Path) -> dict:
    return json.loads(run([
        "ffprobe", "-v", "error", "-show_format", "-show_streams", "-show_chapters",
        "-of", "json", str(path),
    ]))


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def video_packet_hash(path: Path) -> str:
    result = run([
        "ffmpeg", "-hide_banner", "-v", "error", "-i", str(path),
        "-map", "0:v:0", "-c:v", "copy", "-f", "streamhash", "-hash", "sha256", "-",
    ])
    match = re.search(r"SHA256=([0-9a-fA-F]{64})", result)
    if not match:
        raise ValueError(f"No encoded-video SHA-256 returned: {result}")
    return match.group(1).lower()


def check_narration(path: Path, expected_duration: float) -> dict:
    with wave.open(str(path), "rb") as handle:
        configuration = (handle.getframerate(), handle.getnchannels(), handle.getsampwidth(), handle.getcomptype())
        if configuration != (22050, 1, 2, "NONE"):
            raise ValueError(f"Expected 22050 Hz mono PCM16 WAV: {configuration}")
        frames = handle.getnframes()
        data = handle.readframes(frames)
    if len(data) != frames * 2:
        raise ValueError("Narration WAV is truncated or still being written")
    duration = frames / 22050
    if abs(duration - expected_duration) > 0.001:
        raise ValueError(f"Narration is not aligned: {duration:.9f} vs {expected_duration:.9f} s")
    return {"sample_rate": 22050, "channels": 1, "frames": frames, "duration_seconds": duration, "sha256": sha256(path)}


def chapter_identity(chapters: list[dict]) -> list[tuple]:
    return [
        (float(chapter["start_time"]), float(chapter["end_time"]), chapter.get("tags", {}).get("title"))
        for chapter in chapters
    ]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, required=True)
    parser.add_argument("--audio", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--report", type=Path, required=True)
    parser.add_argument("--subtitles", type=Path, required=True)
    arguments = parser.parse_args()
    source = arguments.source.resolve(strict=True)
    audio = arguments.audio.resolve(strict=True)
    destination = arguments.output.resolve()
    report_path = arguments.report.resolve()
    subtitles = arguments.subtitles.resolve(strict=True)
    if source == destination:
        raise ValueError("The original video must be preserved; choose another output file")
    destination.parent.mkdir(parents=True, exist_ok=True)
    report_path.parent.mkdir(parents=True, exist_ok=True)
    logs = destination.parent / "logs"
    logs.mkdir(exist_ok=True)
    old = probe(source)
    expected_duration = float(old["format"]["duration"])
    if not math.isfinite(expected_duration) or expected_duration <= 0:
        raise ValueError("Invalid source duration")
    if len(old.get("chapters", [])) != 22:
        raise ValueError("The original laboratory tour must contain its 22 chapters")
    narration = check_narration(audio, expected_duration)
    original_subtitles_hash = sha256(subtitles)
    original_video_hash = video_packet_hash(source)
    temporary = destination.with_suffix(".encoding.mp4")
    print(f"Replace audio only: {expected_duration:.3f} s; preserve 22 chapters and burned subtitles", flush=True)
    mux_log = run([
        "ffmpeg", "-hide_banner", "-y", "-i", str(source), "-i", str(audio),
        "-map", "0:v:0", "-map", "1:a:0", "-map_metadata", "0", "-map_chapters", "0",
        "-c:v", "copy", "-af", AUDIO_FILTER, "-c:a", "aac", "-b:a", "80k", "-ar", "48000", "-ac", "1",
        "-metadata:s:a:0", "language=fra", "-metadata:s:a:0", "title=Narration française — synthèse neuronale",
        "-t", f"{expected_duration:.9f}", "-movflags", "+faststart", str(temporary),
    ], logs / "neural-remux.log")
    if re.search(r"Non-monoton|corrupt|Invalid", mux_log, re.I):
        raise ValueError("The muxing log contains an unexpected timestamp or media error")
    new = probe(temporary)
    actual_duration = float(new["format"]["duration"])
    if abs(actual_duration - expected_duration) > 0.001:
        raise ValueError(f"Output duration changed: {actual_duration} vs {expected_duration}")
    if chapter_identity(new.get("chapters", [])) != chapter_identity(old["chapters"]):
        raise ValueError("Chapter times or titles changed")
    videos = [stream for stream in new["streams"] if stream["codec_type"] == "video"]
    audios = [stream for stream in new["streams"] if stream["codec_type"] == "audio"]
    if len(videos) != 1 or len(audios) != 1:
        raise ValueError("Expected exactly one video and one audio stream")
    if (videos[0]["codec_name"], videos[0]["width"], videos[0]["height"], videos[0]["pix_fmt"]) != ("h264", 1440, 1080, "yuv420p"):
        raise ValueError("The laboratory video format changed")
    if (audios[0]["codec_name"], audios[0]["sample_rate"], audios[0]["channels"]) != ("aac", "48000", 1):
        raise ValueError("Unexpected AAC narration configuration")
    if any(stream["codec_type"] == "subtitle" for stream in new["streams"]):
        raise ValueError("A subtitle track could duplicate the existing burned captions")
    new_video_hash = video_packet_hash(temporary)
    if new_video_hash != original_video_hash:
        raise ValueError("Encoded video packet SHA-256 changed; the original frames were not preserved")
    if sha256(subtitles) != original_subtitles_hash:
        raise ValueError("The original SRT changed during audio replacement")
    print("Verify full audio/video decode and decoded audio loudness/true peak", flush=True)
    run([
        "ffmpeg", "-hide_banner", "-v", "error", "-xerror", "-threads", "3", "-i", str(temporary),
        "-map", "0:v:0", "-map", "0:a:0", "-f", "null", "-",
    ], logs / "neural-decode.log")
    levels = run([
        "ffmpeg", "-hide_banner", "-i", str(temporary), "-map", "0:a:0", "-af", "ebur128=peak=true",
        "-f", "null", "-",
    ], logs / "neural-true-peak.log")
    peak_match = re.search(r"True peak:\s*Peak:\s*([-+\d.]+) dBFS", levels)
    loudness_match = re.search(r"Integrated loudness:\s*I:\s*([-+\d.]+) LUFS", levels)
    if not peak_match or float(peak_match.group(1)) >= 0:
        raise ValueError("Decoded neural narration has an absent or saturated true peak")
    if temporary.stat().st_size >= 50_000_000:
        raise ValueError("The revised video exceeds the 50 MB delivery budget")
    temporary.replace(destination)
    report = {
        "path": str(destination), "source": str(source), "duration_seconds": actual_duration,
        "bytes": destination.stat().st_size, "sha256": sha256(destination),
        "voice": "Kokoro 82M, fr-fr, ff_siwis",
        "disclosure": "Voix de synthèse neuronale. Aucun enregistrement humain n’a été réalisé pour cette narration.",
        "audio": "AAC, target 80 kbit/s, mono, 48000 Hz",
        "audio_normalization": AUDIO_FILTER,
        "decoded_audio_true_peak_dbfs": float(peak_match.group(1)),
        "decoded_audio_integrated_lufs": float(loudness_match.group(1)) if loudness_match else None,
        "full_decode": "passed", "chapters_identical": True, "chapters": len(new["chapters"]),
        "video_packet_sha256_original": original_video_hash, "video_packet_sha256_new": new_video_hash,
        "video_copy_identical": True, "srt_unchanged": True, "srt_sha256": original_subtitles_hash,
        "burned_subtitles_unchanged": True, "embedded_subtitle_tracks": 0,
        "aligned_narration": narration,
    }
    report_path.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(report, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError, RuntimeError, subprocess.CalledProcessError, wave.Error) as error:
        print(f"ERROR: {error}", file=sys.stderr)
        sys.exit(1)
